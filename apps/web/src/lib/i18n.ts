export function hasUiDictionary(locale: string): boolean {
  return Boolean(MESSAGES[locale] || MESSAGES[baseLocale(locale)]);
}

const overlays = new Map<string, Partial<Messages>>();

export function setMessageOverlay(locale: string, partial: Partial<Messages>) {
  overlays.set(locale, { ...overlays.get(locale), ...partial });
}

export function englishCatalog(): Array<[MessageKey, string]> {
  return (Object.keys(EN) as MessageKey[]).map((key) => [key, EN[key]]);
}

export function t(locale: string, key: MessageKey, vars?: Record<string, string | number>): string {
  const overlay = overlays.get(locale) || overlays.get(baseLocale(locale));
  const dict = MESSAGES[locale] || MESSAGES[baseLocale(locale)];
  const template = overlay?.[key] || dict?.[key] || EN[key];
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = vars[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}
